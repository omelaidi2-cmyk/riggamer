<p>Let''s talk money, because this is where free-to-play games live or die. Arknights: Endfield uses a <strong>pity system</strong> capped at 80 pulls for a guaranteed 6-star operator. The soft pity starts at 50 pulls, meaning your chances increase significantly after the halfway mark.</p>

<p>The important numbers for 2026:</p>
<ul>
  <li><strong>F2P pulls available:</strong> approximately 120 in the first few months (login bonuses, story rewards, event currency)</li>
  <li><strong>Free 6-stars:</strong> Ardelia (login reward, Chapters 1–3), plus seasonal event operators</li>
  <li><strong>Rate-up guarantee:</strong> 50/50 on first pull at pity, guaranteed rate-up on second pity</li>
  <li><strong>Top SS-tier operators:</strong> Arcane, Argent Flow — both obtainable F2P with patience</li>
</ul>

<p>Compared to Genshin Impact (which has the same 50/50 structure but costs more in real terms due to no secondary pity), Endfield is slightly more generous. Compared to mobile Arknights, the rates feel comparable but the lack of a welfare operator every event is a step down.</p>

<p><strong>Verdict on gacha:</strong> 7/10. Competitive rates for the genre, transparent pity system. The lack of monthly event welfare operators is the main weakness.</p>

